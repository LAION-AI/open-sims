export function speechBubble(actor,language=locale){
  const original=actor?.speech?.text||'';
  if(!original||language==='de')return original;
  // Existing SQLite phrase rows are authored in German. Render a short,
  // deterministic contextual English line without mutating those saved rows.
  const context=`${actor.action?.kind||''} ${actor.action?.label||''}`.toLowerCase();
  const group=/argu|fight|conflict|provoke|insult/.test(context)?'conflict':
    /flirt|romanc|kiss|date|love/.test(context)?'romance':
    /part|danc|club|bar/.test(context)?'party':
    /cook|eat|meal|food|dinner|pizza|breakfast/.test(context)?'food':
    /swim|fit|gym|run|sport|exercise/.test(context)?'exercise':
    /sleep|rest|nap/.test(context)?'sleep':
    /school|study|lecture|class|seminar|exam/.test(context)?'study':
    /work|project|task|shift|office|career|job/.test(context)?'work':
    /chat|talk|call|social|friend|gossip|help|play/.test(context)?'social':
    actor.action?.phase==='travel'?'travel':'general';
  const options=speech[group];
  let hash=0;for(const character of `${actor.id||''}:${original}`)hash=(hash*31+character.codePointAt(0))>>>0;
  return options[hash%options.length];
}
export function translate(value,language=locale){
  if(value==null)return '';
  let result=String(value);
  // Single pass prevents replacements from being translated back. Word
  // boundaries avoid changing names such as "Kinderbrook".
  const {from,candidates,lookup}=compiled[language==='de'?'de':'en'];
  if(lookup.has(result))return lookup.get(result);
  // Do not create half-translated long prose by replacing isolated words in
  // canonical journal narratives. Full sentences still translate via the map.
  const found=candidates.filter(pair=>(result.length<=60||pair[from].length>=12)&&result.includes(pair[from]));
  if(!found.length)return result;
  const pattern=new RegExp(found.map(pair=>{
    const source=pair[from].replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
    return `(?<![\\p{L}])${source}(?![\\p{L}])`;
  }).join('|'),'gu');
  result=result.replace(pattern,match=>lookup.get(match)||match);
  return result;
}
function ignored(node){return node.parentElement?.closest('script,style,pre,code,[data-no-i18n]');}
function updateText(node){
  if(!node.nodeValue?.trim()||ignored(node))return;
  if(!originalText.has(node)||node.nodeValue!==renderedText.get(node))originalText.set(node,node.nodeValue);
  const value=translate(originalText.get(node));
  renderedText.set(node,value);
  if(node.nodeValue!==value)node.nodeValue=value;
}
function updateAttrs(element){
  if(element.closest('script,style,pre,code,[data-no-i18n]'))return;
  let originals=originalAttrs.get(element),rendered=renderedAttrs.get(element);
  if(!originals){originals={};rendered={};originalAttrs.set(element,originals);renderedAttrs.set(element,rendered);}
  for(const attr of attrs){
    if(!element.hasAttribute(attr))continue;
    const current=element.getAttribute(attr);
    if(!(attr in originals)||current!==rendered[attr])originals[attr]=current;
    const value=translate(originals[attr]);rendered[attr]=value;
    if(current!==value)element.setAttribute(attr,value);
  }
}
export function localize(root=document){
  if(root.nodeType===3){updateText(root);return;}
  if(root.nodeType!==1&&root.nodeType!==9)return;
  if(root.nodeType===1)updateAttrs(root);
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const node=walker.currentNode;
    if(node.nodeType===3)updateText(node);else updateAttrs(node);
  }
  document.documentElement.lang=locale;
  document.querySelectorAll('[data-language]').forEach(button=>{
    const active=button.dataset.language===locale;
    button.classList.toggle('active',active);
    button.setAttribute('aria-pressed',String(active));
  });
}
export function setLocale(next){
  if(next!=='en'&&next!=='de')return;
  locale=next;
  try{localStorage.setItem(STORAGE_KEY,next)}catch{}
  localize();
  listeners.forEach(listener=>listener(next));
}
export function onLocaleChange(listener){listeners.add(listener);return ()=>listeners.delete(listener);}
export function initI18n(){
  localize();
  document.addEventListener('click',event=>{
    const button=event.target.closest('[data-language]');
    if(button)setLocale(button.dataset.language);
  });
  const observer=new MutationObserver(records=>{
    for(const record of records){
      if(record.type==='characterData')updateText(record.target);
      else if(record.type==='attributes')updateAttrs(record.target);
      else for(const node of record.addedNodes)localize(node);
    }
  });
  observer.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:attrs});
  return observer;
}
